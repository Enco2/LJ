package com.enco.literal;

public class LiteralQuantity {
    public static void main(String[] args) {
        String name = "霸王龙";
        int age = 18;
        double height = 11.5;
        char sex = '公';

        System.out.println("姓名：" + name + "\n" + "年龄：" + age + "\n" + "身高：" + height + "\n" + "性别：" + sex);

    }
}
